/**
 * Runs the WordNet and CMUdict checks over db/vocabulary/*.jsonl and writes
 * db/vocabulary/lexicon-checks.json (committed, so the app and seed never need the
 * dictionary data). Development only: needs the dev dependencies wordnet-db and
 * cmu-pronouncing-dictionary.
 *
 *   npm run vocab:check            # recompute, write the file, print a report
 *   npm run vocab:check -- --verify  # exit 1 if the committed file is out of date
 *
 * The output is deterministic (no timestamps), so the same input always gives the
 * same file.
 */

import fs from 'node:fs';
import { createRequire } from 'node:module';
import { loadWordNet, checkEntry, loadCmudict, pronounce } from './lexicon.mjs';

const require = createRequire(import.meta.url);
const bank = require('./bank.js');

export async function computeChecks(rawEntries = bank.loadRawEntries()) {
  const wn = loadWordNet();
  const cmu = await loadCmudict();
  const entries = {};
  for (const { raw } of rawEntries) {
    if (!raw?.word) continue;
    const k = raw.word.normalize('NFKC').trim().toLocaleLowerCase('en');
    entries[k] = { ...checkEntry(wn, bank.checkInput(raw)), pronunciation: pronounce(cmu, raw.word) };
  }
  return {
    note: 'Generated by scripts/vocabulary/checkLexicon.mjs from WordNet 3.1 and the CMU Pronouncing Dictionary. Do not edit by hand.',
    wordnetVersion: wn.version,
    inputHash: bank.checksInputHash(rawEntries),
    entries: Object.fromEntries(Object.keys(entries).sort().map((k) => [k, entries[k]])),
  };
}

export const serialize = (checks) => `${JSON.stringify(checks, null, 1)}\n`;

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, '/')}` || process.argv[1]?.endsWith('checkLexicon.mjs')) {
  const checks = await computeChecks();
  if (process.argv.includes('--verify')) {
    const current = fs.existsSync(bank.CHECKS_FILE) ? fs.readFileSync(bank.CHECKS_FILE, 'utf8') : '';
    if (current !== serialize(checks)) {
      console.error('db/vocabulary/lexicon-checks.json is out of date: run npm run vocab:check');
      process.exit(1);
    }
    console.log('lexicon-checks.json is up to date');
  } else {
    fs.writeFileSync(bank.CHECKS_FILE, serialize(checks));
    const { parsed, errors } = bank.parseBank();
    const official = bank.officialPairs();
    let published = 0;
    const lines = [];
    for (const { row, entry } of parsed) {
      const a = bank.assess(entry, checks.entries[entry.normalized_word], official);
      if (a.publish) published += 1;
      if (a.failures.length) lines.push(`FAIL  ${row} ${entry.word}: ${a.failures.join('; ')}`);
      if (a.unconfirmed.length) lines.push(`note  ${row} ${entry.word}: unconfirmed ${a.unconfirmed.join(', ')}`);
    }
    const noPron = parsed.filter(({ entry }) => !checks.entries[entry.normalized_word]?.pronunciation).map(({ entry }) => entry.word);
    console.log(lines.join('\n'));
    console.log(`\n${parsed.length} entries parsed, ${errors.length} validation errors, ${published} publishable, ${parsed.length - published} held back`);
    console.log(`no CMU pronunciation (left blank, not guessed): ${noPron.length ? noPron.join(', ') : 'none'}`);
    for (const e of errors) console.log(`ERROR ${e.row} ${e.field}: ${e.code} ${e.message}`);
  }
}
