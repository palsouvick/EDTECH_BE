// English: articles (a, an, the, no article). The sentence and options are
// English; the instruction and the explanation are also given in Bengali.

const ALL = ['a', 'an', 'the', 'No article'];
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

// Article blank: the three other article choices are the wrong options.
const A = (d, s, a, en, bn) => {
  const start = s.trimStart().startsWith('___');
  const fix = (x) => (start && x !== 'No article' ? cap(x) : x);
  const ans = a === 'No article' ? a : a.toLowerCase();
  return {
    d,
    q: [`Fill in the blank: ${s}`, `শূন্যস্থান পূরণ করো: ${s}`],
    a: [fix(ans), fix(ans)],
    w: ALL.filter((x) => x !== ans).map((x) => [fix(x), fix(x)]),
    e: [en, bn],
  };
};

